"""The seven tetrominoes and their rotations, as cell offsets and as row bitmasks.

A shape is a tuple of (x, y) offsets with x growing right and y growing down from the top-left
of its bounding box. Rotations are generated by turning the spawn shape clockwise and dropping
duplicates, which gives the classic counts: 1 for O, 2 for I, S and Z, 4 for T, J and L.
No Kodi imports.
"""

SPAWN = {
    'I': ((0, 0), (1, 0), (2, 0), (3, 0)),
    'O': ((0, 0), (1, 0), (0, 1), (1, 1)),
    'T': ((1, 0), (0, 1), (1, 1), (2, 1)),
    'S': ((1, 0), (2, 0), (0, 1), (1, 1)),
    'Z': ((0, 0), (1, 0), (1, 1), (2, 1)),
    'J': ((0, 0), (0, 1), (1, 1), (2, 1)),
    'L': ((2, 0), (0, 1), (1, 1), (2, 1)),
}

TYPES = ('I', 'O', 'T', 'S', 'Z', 'J', 'L')


def normalise(shape):
    """Move a shape's bounding box to the origin."""
    min_x = min(x for x, _y in shape)
    min_y = min(y for _x, y in shape)
    return tuple(sorted((x - min_x, y - min_y) for x, y in shape))


def turned(shape):
    """The shape turned a quarter clockwise inside its bounding box."""
    height = max(y for _x, y in shape) + 1
    return normalise(tuple((height - 1 - y, x) for x, y in shape))


def rotations(shape):
    out = [normalise(shape)]
    for _ in range(3):
        nxt = turned(out[-1])
        if nxt in out:
            break
        out.append(nxt)
    return tuple(out)


ROTATIONS = dict((name, rotations(shape)) for name, shape in SPAWN.items())


def width(shape):
    return max(x for x, _y in shape) + 1


def height(shape):
    return max(y for _x, y in shape) + 1


def masks(shape):
    """Row bitmasks: tuple of (dy, mask) with bit x set for a filled cell at that row."""
    rows = {}
    for x, y in shape:
        rows[y] = rows.get(y, 0) | (1 << x)
    return tuple(sorted(rows.items()))


def cells(shape, x, y):
    return [(x + dx, y + dy) for dx, dy in shape]
