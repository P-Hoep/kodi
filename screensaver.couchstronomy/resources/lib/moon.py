def _poly(t, *c):
    out = 0.0
    for k in reversed(c):
        out = out * t + k
    return out


def ecliptic_of_date(jd_tt):
    """Geocentric (lon, lat, distance km), mean ecliptic and equinox of date."""
    t = astro.centuries(jd_tt)
    lp = _poly(t, 218.3164477, 481267.88123421, -0.0015786, 1 / 538841.0, -1 / 65194000.0) * D2R
    d = _poly(t, 297.8501921, 445267.1114034, -0.0018819, 1 / 545868.0, -1 / 113065000.0) * D2R
    m = _poly(t, 357.5291092, 35999.0502909, -0.0001536, 1 / 24490000.0) * D2R
    mp = _poly(t, 134.9633964, 477198.8675055, 0.0087414, 1 / 69699.0, -1 / 14712000.0) * D2R
    f = _poly(t, 93.2720950, 483202.0175233, -0.0036539, -1 / 3526000.0, 1 / 863310000.0) * D2R
    a1 = (119.75 + 131.849 * t) * D2R
    a2 = (53.09 + 479264.290 * t) * D2R
    a3 = (313.45 + 481266.484 * t) * D2R
    e = _poly(t, 1.0, -0.002516, -0.0000074)
    ecc = (1.0, e, e * e)
    sl = 3958 * math.sin(a1) + 1962 * math.sin(lp - f) + 318 * math.sin(a2)
    sr = 0.0
    sb = (-2235 * math.sin(lp) + 382 * math.sin(a3) + 175 * math.sin(a1 - f)
          + 175 * math.sin(a1 + f) + 127 * math.sin(lp - mp) - 115 * math.sin(lp + mp))
    for cd, cm, cmp, cf, l_amp, r_amp in TERMS_LR:
        arg = cd * d + cm * m + cmp * mp + cf * f
        k = ecc[abs(cm)]
        sl += l_amp * k * math.sin(arg)
        sr += r_amp * k * math.cos(arg)
    for cd, cm, cmp, cf, b_amp in TERMS_B:
        sb += b_amp * ecc[abs(cm)] * math.sin(cd * d + cm * m + cmp * mp + cf * f)
    lon = (lp + sl * 1e-6 * D2R) % astro.TAU
    lat = sb * 1e-6 * D2R
    return lon, lat, 385000.56 + sr * 1e-3


def geocentric_of_date(frame):
    """Apparent geocentric position, true equator of date, km."""
    lon, lat, dist = ecliptic_of_date(frame.jd_tt)
    v = astro.vec(lon + frame.dpsi, lat, dist)
    return astro.ecliptic_to_equatorial(v, frame.eps)
