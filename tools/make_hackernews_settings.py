"""Generate the Hacker News screensaver's settings.xml and strings.po from its config table.

  python3 tools/make_hackernews_settings.py

resources/lib/config.py holds every setting, its string ids and every piece of on-screen text;
this keeps the XML and the .po file exactly in step with it. Run it after editing the table.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
ADDON = os.path.join(ROOT, 'screensaver.hackernews')
sys.path.insert(0, ADDON)

from resources.lib import config  # noqa: E402


def xml_escape(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def default_text(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    return str(value)


def control(setting):
    s = setting
    if s['type'] == 'boolean':
        return '<control type="toggle"/>'
    if s['type'] == 'slider':
        return ('<constraints><minimum>%d</minimum><step>%d</step><maximum>%d</maximum></constraints>\n'
                '          <control type="slider" format="integer"><popup>false</popup></control>'
                % (s['min'], s['step'], s['max']))
    if s['type'] == 'options':
        options = '\n'.join('              <option label="%d">%d</option>' % (label, index)
                            for index, label in enumerate(s['options']))
        return ('<constraints><options>\n%s\n            </options></constraints>\n'
                '          <control type="spinner" format="string"/>' % options)
    if s['type'] == 'action':
        data = 'RunScript(special://home/addons/%s/screensaver.py,%s)' % (
            config.ADDON_ID, s['command'])
        return ('<data>%s</data>\n'
                '          <control type="button" format="action"><close>true</close></control>'
                % xml_escape(data))
    raise ValueError(s['type'])


def settings_xml():
    lines = ['<?xml version="1.0" encoding="utf-8" standalone="yes"?>',
             '<!-- Generated by tools/make_hackernews_settings.py; edit the table in '
             'resources/lib/config.py. -->',
             '<settings version="1">',
             '  <section id="%s">' % config.ADDON_ID]
    for index, (label, settings) in enumerate(config.CATEGORIES):
        lines.append('    <category id="c%d" label="%d">' % (index, label))
        lines.append('      <group id="1">')
        for setting in settings:
            kind = 'integer' if setting['type'] in ('slider', 'options') else setting['type']
            lines.append('        <setting id="%s" type="%s" label="%d">' %
                         (setting['id'], kind, setting['label']))
            lines.append('          <level>0</level>')
            if setting['type'] != 'action':
                lines.append('          <default>%s</default>' % default_text(setting['default']))
            lines.append('          ' + control(setting))
            lines.append('        </setting>')
        lines.append('      </group>')
        lines.append('    </category>')
    lines.append('  </section>')
    lines.append('</settings>')
    return '\n'.join(lines) + '\n'


def strings_po():
    lines = ['# Kodi Media Center language file',
             '# Addon Name: %s' % config.ADDON_NAME,
             '# Addon id: %s' % config.ADDON_ID,
             '# Generated by tools/make_hackernews_settings.py',
             'msgid ""',
             'msgstr ""',
             '"Content-Type: text/plain; charset=UTF-8\\n"',
             '"Language: en_GB\\n"',
             '']
    for string_id in sorted(config.STRINGS):
        lines.append('msgctxt "#%d"' % string_id)
        lines.append('msgid "%s"' % config.STRINGS[string_id]
                     .replace('\\', '\\\\').replace('"', '\\"'))
        lines.append('msgstr ""')
        lines.append('')
    return '\n'.join(lines)


def main():
    language = os.path.join(ADDON, 'resources', 'language', 'resource.language.en_gb')
    with open(os.path.join(ADDON, 'resources', 'settings.xml'), 'w', encoding='utf-8') as handle:
        handle.write(settings_xml())
    with open(os.path.join(language, 'strings.po'), 'w', encoding='utf-8') as handle:
        handle.write(strings_po())
    print('->%s/resources/settings.xml' % config.ADDON_ID)
    print('->%s/resources/language/resource.language.en_gb/strings.po' % config.ADDON_ID)


if __name__ == '__main__':
    main()
