"""Generate settings.xml and strings.po for script.opentrivia and screensaver.opentrivia from
the one table in script.module.opentrivia/lib/opentrivia/config.py, plus the library's strings.po
with the on-screen text (config.STRINGS, ids 32000 and up).

Run: python3 tools/make_settings_opentrivia.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, os.path.join(ROOT, 'script.module.opentrivia', 'lib'))
sys.path.insert(0, HERE)

from make_settings import write  # noqa: E402
from opentrivia import APP_ID, LIBRARY_ID, SCREENSAVER_ID, config  # noqa: E402

GENERATOR = 'tools/make_settings_opentrivia.py'


def table(who):
    out = []
    for title, rows in config.SETTINGS:
        settings = [dict((k, v) for k, v in s.items() if k != 'who')
                    for s in rows if s.get('who', 'both') in ('both', who)]
        if settings:
            out.append((title, settings))
    return out


def library_strings():
    folder = os.path.join(ROOT, LIBRARY_ID, 'resources', 'language', 'resource.language.en_gb')
    os.makedirs(folder, exist_ok=True)
    po = ['# Kodi Media Center language file', '# Addon Name: OpenTrivia library', '# Addon id: %s' % LIBRARY_ID,
          '# Generated by %s' % GENERATOR, 'msgid ""', 'msgstr ""',
          '"Content-Type: text/plain; charset=UTF-8\\n"', '"Language: en_GB\\n"', '']
    for sid in sorted(config.STRINGS):
        po += ['msgctxt "#%d"' % sid, 'msgid "%s"' % config.STRINGS[sid].replace('"', '\\"'), 'msgstr ""', '']
    with open(os.path.join(folder, 'strings.po'), 'w') as handle:
        handle.write('\n'.join(po))
    print('library strings: %d' % len(config.STRINGS))


def main():
    write(os.path.join(ROOT, APP_ID), APP_ID, 'OpenTrivia', table('app'), GENERATOR)
    write(os.path.join(ROOT, SCREENSAVER_ID), SCREENSAVER_ID, 'OpenTrivia Screensaver', table('ss'), GENERATOR)
    library_strings()


if __name__ == '__main__':
    main()
