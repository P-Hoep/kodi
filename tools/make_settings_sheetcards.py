"""Generate settings.xml + strings.po for script.sheetcards and screensaver.sheetcards from the
one table in script.module.sheetcards/lib/sheetcards/config.py, and the library's strings.po
with the on-screen text (config.STRINGS, ids 32000 and up).

Run: python3 tools/make_settings_sheetcards.py

In the screensaver, the settings it shares with the app are hidden while "Use the Sheetcards
app's settings" is on and the app is installed; that toggle itself shows only when the app is.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, os.path.join(ROOT, 'script.module.sheetcards', 'lib'))
sys.path.insert(0, HERE)

from make_settings import write  # noqa: E402
from sheetcards import APP_ID, LIBRARY_ID, SCREENSAVER_ID, config  # noqa: E402

GENERATOR = 'tools/make_settings_sheetcards.py'
HAS_APP = 'System.HasAddon(%s)' % APP_ID


def condition(rule):
    """A make_settings visibility rule as a bare <condition>."""
    if isinstance(rule, str):
        return '<condition setting="%s">true</condition>' % rule
    if len(rule) == 3:
        return '<condition setting="%s" operator="!is">%s</condition>' % (rule[0], rule[2])
    return '<condition setting="%s">%s</condition>' % rule


def own_settings():
    """Screensaver: shown when it is not borrowing the app's settings."""
    return ('<or><condition setting="use_app_settings">false</condition>'
            '<condition on="property" name="InfoBool">!%s</condition></or>' % HAS_APP)


def deps(inner):
    return '<dependencies><dependency type="visible">%s</dependency></dependencies>' % inner


def table(who, addon_id):
    out = []
    for title, rows in config.CATEGORIES:
        settings = []
        for row in rows:
            if row['who'] not in ('both', who):
                continue
            s = dict((k, v) for k, v in row.items() if k not in ('who', 'local', 'command'))
            if row['type'] == 'action':
                s['data'] = 'RunScript(special://home/addons/%s/default.py,%s)' % (addon_id, row['command'])
            if who == 'ss':
                if row['id'] == 'use_app_settings':
                    s['visible'] = deps('<condition on="property" name="InfoBool">%s</condition>' % HAS_APP)
                elif not row.get('local') and row['id'] != 'clear_cache':
                    if row.get('visible'):
                        s['visible'] = deps('<and>%s%s</and>' % (condition(row['visible']), own_settings()))
                    else:
                        s['visible'] = deps(own_settings())
            settings.append(s)
        if settings:
            out.append((title, settings))
    return out


def main():
    for addon_id, who, name in ((APP_ID, 'app', 'Sheetcards'), (SCREENSAVER_ID, 'ss', 'Sheetcards Screensaver')):
        write(os.path.join(ROOT, addon_id), addon_id, name, table(who, addon_id), GENERATOR)
    folder = os.path.join(ROOT, LIBRARY_ID, 'resources', 'language', 'resource.language.en_gb')
    os.makedirs(folder, exist_ok=True)
    po = ['# Kodi Media Center language file', '# Addon Name: Sheetcards library', '# Addon id: %s' % LIBRARY_ID,
          '# Generated by %s' % GENERATOR, 'msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"',
          '"Language: en_GB\\n"', '']
    for sid in sorted(config.STRINGS):
        po += ['msgctxt "#%d"' % sid, 'msgid "%s"' % config.STRINGS[sid].replace('"', '\\"'), 'msgstr ""', '']
    with open(os.path.join(folder, 'strings.po'), 'w') as handle:
        handle.write('\n'.join(po))
    print('library strings: %d' % len(config.STRINGS))


if __name__ == '__main__':
    main()
