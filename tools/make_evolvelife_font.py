"""Bake the EvolveLife HUD font (Inter SemiBold, SIL Open Font License 1.1) into
screensaver.evolvelife/src/Font.h: an alpha atlas of printable ASCII plus glyph metrics, so the
native add-on needs no font files or font library at run time.

Run (needs Pillow and Inter[opsz,wght].ttf from https://github.com/rsms/inter, cached by the Word
Clock tools in tools/.wordclock-fonts/):
  python3 tools/make_evolvelife_font.py

The atlas is 1024 x 256 (a power of two, so GLES 2 can mipmap it) and is stored run-length coded:
a 0 byte is followed by the length of a run of zeros (1-255); any other byte is a literal alpha.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, '.wordclock-fonts', 'Inter[opsz,wght].ttf')
OUT = os.path.join(HERE, '..', 'screensaver.evolvelife', 'src', 'Font.h')
SIZE = 44
W, H = 1024, 256
PAD = 3


def main():
    if not os.path.exists(FONT):
        sys.exit('missing %s (run tools/make_wordclock_media.py or download Inter)' % FONT)
    font = ImageFont.truetype(FONT, SIZE)
    font.set_variation_by_axes([24, 600])  # optical size 24, SemiBold
    ascent, descent = font.getmetrics()
    atlas = Image.new('L', (W, H), 0)
    draw = ImageDraw.Draw(atlas)
    glyphs = []
    x, y, row_h = PAD, PAD, 0
    for code in range(32, 127):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        gw, gh = max(right - left, 0), max(bottom - top, 0)
        adv = font.getlength(ch)
        if x + gw + PAD > W:
            x, y = PAD, y + row_h + PAD
            row_h = 0
        if y + gh + PAD > H:
            sys.exit('atlas too small')
        if gw and gh:
            draw.text((x - left, y - top), ch, font=font, fill=255)
        # x, y, w, h in the atlas; xoff, yoff from the pen (baseline) to the glyph's top left
        glyphs.append((x, y, gw, gh, left, top - ascent, adv))
        x += gw + PAD
        row_h = max(row_h, gh)

    data = atlas.tobytes()
    rle = bytearray()
    i = 0
    while i < len(data):
        if data[i] == 0:
            n = 1
            while i + n < len(data) and data[i + n] == 0 and n < 255:
                n += 1
            rle += bytes((0, n))
            i += n
        else:
            rle.append(data[i])
            i += 1

    out = []
    out.append('// Generated by tools/make_evolvelife_font.py - do not edit.')
    out.append('// Inter SemiBold (https://github.com/rsms/inter), SIL Open Font License 1.1,')
    out.append('// Copyright (c) 2016 The Inter Project Authors. See LICENSE.txt.')
    out.append('#pragma once')
    out.append('#include <cstdint>')
    out.append('namespace evo { namespace font {')
    out.append('constexpr int kAtlasW = %d, kAtlasH = %d, kSize = %d, kAscent = %d, kDescent = %d;'
               % (W, H, SIZE, ascent, descent))
    out.append('struct Glyph { int16_t x, y, w, h, xoff, yoff; float adv; };')
    out.append('const Glyph kGlyphs[95] = {')
    for g in glyphs:
        out.append('  {%d, %d, %d, %d, %d, %d, %.3ff},' % g)
    out.append('};')
    out.append('constexpr unsigned kRleSize = %d;' % len(rle))
    out.append('const uint8_t kRle[kRleSize] = {')
    for k in range(0, len(rle), 24):
        out.append('  ' + ','.join(str(b) for b in rle[k:k + 24]) + ',')
    out.append('};')
    out.append('}} // namespace evo::font')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote %s: %d glyphs, %d bytes RLE (atlas rows used: %d)' % (OUT, len(glyphs), len(rle), y + row_h))


if __name__ == '__main__':
    main()
