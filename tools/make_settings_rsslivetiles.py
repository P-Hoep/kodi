"""Generate settings.xml + strings.po for script.rsslivetiles and screensaver.rsslivetiles from
the one table in script.module.rsslivetiles/lib/rsslivetiles/config.py, and the library's
strings.po with the on-screen text (config.STRINGS, ids 32000 and up).

Run: python3 tools/make_settings_rsslivetiles.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, os.path.join(ROOT, 'script.module.rsslivetiles', 'lib'))
sys.path.insert(0, HERE)

from make_settings import write  # noqa: E402
from rsslivetiles import APP_ID, LIBRARY_ID, SCREENSAVER_ID, config  # noqa: E402

GENERATOR = 'tools/make_settings_rsslivetiles.py'


def table(who, addon_id):
    out = []
    for title, rows in config.CATEGORIES:
        settings = []
        for row in rows:
            if row['who'] not in ('both', who):
                continue
            s = dict((k, v) for k, v in row.items() if k not in ('who', 'command'))
            if row['type'] == 'action':
                s['data'] = 'RunScript(special://home/addons/%s/default.py,%s)' % (addon_id, row['command'])
            settings.append(s)
        if settings:
            out.append((title, settings))
    return out


def main():
    for addon_id, who, name in ((APP_ID, 'app', 'RSS Live Tiles'),
                                (SCREENSAVER_ID, 'ss', 'RSS Live Tiles Screensaver')):
        write(os.path.join(ROOT, addon_id), addon_id, name, table(who, addon_id), GENERATOR)
    folder = os.path.join(ROOT, LIBRARY_ID, 'resources', 'language', 'resource.language.en_gb')
    os.makedirs(folder, exist_ok=True)
    po = ['# Kodi Media Center language file', '# Addon Name: RSS Live Tiles library', '# Addon id: %s' % LIBRARY_ID,
          '# Generated by %s' % GENERATOR, 'msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"',
          '"Language: en_GB\\n"', '']
    for sid in sorted(config.STRINGS):
        po += ['msgctxt "#%d"' % sid, 'msgid "%s"' % config.STRINGS[sid].replace('"', '\\"'), 'msgstr ""', '']
    with open(os.path.join(folder, 'strings.po'), 'w') as handle:
        handle.write('\n'.join(po))
    print('library strings: %d' % len(config.STRINGS))


if __name__ == '__main__':
    main()
