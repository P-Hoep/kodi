"""Generate Math Clock's glyph images, their metrics and the add-on icon.

Each glyph is rendered once from the Computer Modern (BaKoMa) TrueType fonts that ship
with matplotlib, the same faces MathJax and LaTeX use, as a white-on-transparent PNG
cropped to its ink. The Kodi add-on positions and tints these images itself, so it
needs no TeX installation and no font rendering at run time.

  python3 tools/make_mathclock_media.py      (needs Pillow and matplotlib)

Writes resources/media/glyphs/*.png, resources/lib/glyphs.py (metrics) and icon.png.
"""

import os
import sys

import matplotlib
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', 'screensaver.math.clock'))
FONTS = os.path.join(os.path.dirname(matplotlib.__file__), 'mpl-data', 'fonts', 'ttf')
EM = 200      # pixels per em in the glyph images
PAD = 3       # transparent border around each glyph, so scaling never clips the ink

# name -> (font, character). BaKoMa moves TeX's codes 0x00-0x20 up to 0xA1-0xC4.
GLYPHS = {}
for c in '0123456789':
    GLYPHS['rm_' + c] = ('cmr10', c)
for c in 'abcdefghijklmnopqrstuvwxyz':
    GLYPHS['rm_' + c] = ('cmr10', c)
for c in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ':
    GLYPHS['mi_' + (c if c.islower() else 'cap_' + c)] = ('cmmi10', c)
GLYPHS.update({
    'rm_plus': ('cmr10', '+'), 'rm_equal': ('cmr10', '='), 'rm_lparen': ('cmr10', '('),
    'rm_rparen': ('cmr10', ')'), 'rm_lbrack': ('cmr10', '['), 'rm_rbrack': ('cmr10', ']'),
    'rm_exclam': ('cmr10', '!'), 'rm_percent': ('cmr10', '%'), 'rm_colon': ('cmr10', ':'),
    'mi_comma': ('cmmi10', '\x3b'), 'mi_period': ('cmmi10', '\x3a'),
    'sy_minus': ('cmsy10', '\xa1'), 'sy_cdot': ('cmsy10', '\xa2'), 'sy_times': ('cmsy10', '\xa3'),
    'sy_div': ('cmsy10', '\xa5'), 'sy_pm': ('cmsy10', '\xa7'), 'sy_vert': ('cmsy10', '\x6a'),
    'sy_lfloor': ('cmsy10', '\x62'), 'sy_rfloor': ('cmsy10', '\x63'), 'sy_surd': ('cmsy10', '\x70'),
    'ex_sum_text': ('cmex10', '\x50'), 'ex_sum': ('cmex10', '\x58'),
    'mi_less': ('cmmi10', '<'), 'mi_greater': ('cmmi10', '>'), 'sy_leq': ('cmsy10', '\u2219'),
    'sy_geq': ('cmsy10', '\xb8'), 'sy_circ': ('cmsy10', '\xb1'),
})
# Larger sizes of the delimiters and the radical (matplotlib's BaKoMa size table).
SIZED = {
    'lparen': ['\xa1', '\xb3', '\xb5', '\xc3'], 'rparen': ['\xa2', '\xb4', '\xb6', '\x21'],
    'lfloor': ['\xa5', '\x6a', '\xb9', '\x24'], 'rfloor': ['\xa6', '\x6b', '\xba', '\x25'],
    'surd': ['\x70', '\x71', '\x72', '\x73'],
    'lbrack': ['\xa3', '\x68', '\x22'], 'rbrack': ['\xa4', '\x69', '\x23'],
}
for base, chars in SIZED.items():
    for i, ch in enumerate(chars):
        GLYPHS['ex_%s%d' % (base, i + 1)] = ('cmex10', ch)


def render(font, ch):
    # font.getbbox always reaches the baseline, so crop to the ink actually drawn.
    fx0, fy0, fx1, fy1 = font.getbbox(ch, anchor='ls')
    canvas = Image.new('L', (fx1 - fx0 + 20, fy1 - fy0 + 20), 0)
    ox, oy = 10 - fx0, 10 - fy0                       # where the origin lands on the canvas
    ImageDraw.Draw(canvas).text((ox, oy), ch, font=font, fill=255, anchor='ls')
    ix0, iy0, ix1, iy1 = canvas.getbbox()
    x0, y0, x1, y1 = ix0 - ox, iy0 - oy, ix1 - ox, iy1 - oy
    img = Image.new('L', (x1 - x0 + 2 * PAD, y1 - y0 + 2 * PAD), 0)
    img.paste(canvas.crop((ix0, iy0, ix1, iy1)), (PAD, PAD))
    rgba = Image.new('RGBA', img.size, (255, 255, 255, 0))
    rgba.putalpha(img)
    # Metrics in em: advance, then the image's box (padding included) relative to the
    # origin, y up from the baseline.
    metrics = (font.getlength(ch) / EM, (x0 - PAD) / EM, (-y0 + PAD) / EM, (x1 + PAD) / EM, (-y1 - PAD) / EM)
    return rgba, metrics


def make_glyphs():
    out = os.path.join(ROOT, 'resources', 'media', 'glyphs')
    if not os.path.isdir(out):
        os.makedirs(out)
    for name in os.listdir(out):
        if name.endswith('.png'):
            os.remove(os.path.join(out, name))
    fonts = {}
    rows = []
    for name in sorted(GLYPHS):
        face, ch = GLYPHS[name]
        if face not in fonts:
            fonts[face] = ImageFont.truetype(os.path.join(FONTS, face + '.ttf'), EM)
        img, m = render(fonts[face], ch)
        img.save(os.path.join(out, name + '.png'), optimize=True)
        rows.append('    %r: (%s),' % (name, ', '.join('%.4f' % v for v in m)))
    src = ['"""Glyph metrics, generated by tools/make_mathclock_media.py; do not edit.',
           '',
           'name -> (advance, left, top, right, bottom) in em. left..right and bottom..top are',
           'the edges of media/glyphs/<name>.png relative to the glyph origin, y up from the',
           'baseline. Every image has PAD em of transparent border on each side."""', '',
           'PAD = %.4f' % (PAD / float(EM)), '', 'GLYPHS = {'] + rows + ['}', '']
    with open(os.path.join(ROOT, 'resources', 'lib', 'glyphs.py'), 'w') as handle:
        handle.write('\n'.join(src))
    print('%d glyphs' % len(rows))


def draw_box(img, box, x, baseline, em, colour):
    """Draw a texmath Box onto a Pillow RGBA image, as the add-on does with Kodi controls."""
    glyph_dir = os.path.join(ROOT, 'resources', 'media', 'glyphs')
    draw = ImageDraw.Draw(img)
    for name, left, top, w, h in box.items:
        rect = (int(round(x + left * em)), int(round(baseline - top * em)))
        pw, ph = max(1, int(round(w * em))), max(1, int(round(h * em)))
        if name is None:
            draw.rectangle([rect, (rect[0] + pw - 1, rect[1] + ph - 1)], fill=colour)
            continue
        g = Image.open(os.path.join(glyph_dir, name + '.png')).resize((pw, ph), Image.LANCZOS)
        tint = Image.new('RGBA', g.size, colour + (0,))
        tint.putalpha(g.getchannel('A'))
        img.alpha_composite(tint, rect)


def make_icon():
    """Render the icon with the add-on's own layout engine: a clock face of equations."""
    sys.path.insert(0, ROOT)
    from resources.lib import texmath  # noqa: E402
    size = 512
    img = Image.new('RGBA', (size, size), (12, 14, 20, 255))
    lines = [(r'\sqrt{100}', 0.40, (240, 240, 240)), (r'7 \times 5', 0.68, (240, 240, 240))]
    draw = ImageDraw.Draw(img)
    draw.line([(70, int(size * 0.53)), (size - 70, int(size * 0.53))], fill=(60, 64, 74), width=3)
    for latex, cy, colour in lines:
        box = texmath.typeset(latex)
        em = min(150.0, (size - 80) / box.width)
        draw_box(img, box, (size - box.width * em) / 2, size * cy + (box.height - box.depth) / 2 * em, em, colour)
    img.convert('RGB').save(os.path.join(ROOT, 'icon.png'), optimize=True)
    white = Image.new('RGBA', (8, 8), (255, 255, 255, 255))
    white.save(os.path.join(ROOT, 'resources', 'media', 'white.png'))
    print('icon.png')


if __name__ == '__main__':
    make_glyphs()
    make_icon()
