"""Compile the Sand Clock glyph masks (screensaver.sandclock/resources/media/fonts/fonts.json, written by
tools/make_sandclock_media.py) into screensaver.sandclock_v2/src/Glyphs.h, so the native add-on needs no
font files or JSON parser at run time.

Run:
  python3 tools/make_sandclock_v2_fonts.py

Each glyph is stored as rows of runs: for every row, a run count followed by (start, length) pairs.
Only the Regular (1) and Bold (2) weights are kept: Light strokes hold too little sand.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'screensaver.sandclock', 'resources', 'media', 'fonts', 'fonts.json')
OUT = os.path.join(HERE, '..', 'screensaver.sandclock_v2', 'src', 'Glyphs.h')

# The same order as the Sand Clock add-ons (FONT_FOLDERS in screensaver.sandclock.gl/src/sand.cpp).
FONTS = ['inter', 'montserrat', 'orbitron', 'pixelify', 'doto', 'jetbrains', 'comfortaa', 'playfair', 'stencil']
WEIGHTS = ['1', '2']
CHARS = '0123456789:'


def main():
    data = json.load(open(SRC))
    words = []        # one uint16 stream for everything
    glyphs = []       # (font, weight, char) -> (offset, w, h)
    faces = []        # (h, digit_w, colon_w)
    for f in FONTS:
        for wt in WEIGHTS:
            d = data[f][wt]
            faces.append((d['h'], d['digit_w'], d['colon_w']))
            for ch in CHARS:
                w, rows = d['masks'][ch]
                off = len(words)
                for row in rows:
                    words.append(len(row))
                    for start, length in row:
                        words.extend((start, length))
                glyphs.append((off, w, len(rows)))
    lines = ['// Generated by tools/make_sandclock_v2_fonts.py from the Sand Clock fonts.json; do not edit.',
             '#pragma once', '#include <cstdint>', '', 'namespace sandclock2', '{', '',
             'constexpr int kNumFonts = %d;' % len(FONTS), 'constexpr int kNumWeights = %d;' % len(WEIGHTS),
             'constexpr int kNumChars = %d; // 0-9 and the colon' % len(CHARS), '',
             'struct Face', '{', '  int h, digitW, colonW;', '};', '',
             'struct Glyph', '{', '  uint32_t offset;', '  uint16_t w, h;', '};', '',
             'const Face kFaces[kNumFonts * kNumWeights] = {']
    lines += ['  {%d, %d, %d},' % face for face in faces]
    lines += ['};', '', 'const Glyph kGlyphs[kNumFonts * kNumWeights * kNumChars] = {']
    for i in range(0, len(glyphs), 4):
        lines.append('  ' + ' '.join('{%d, %d, %d},' % g for g in glyphs[i:i + 4]))
    lines += ['};', '', 'const uint16_t kRuns[%d] = {' % len(words)]
    for i in range(0, len(words), 24):
        lines.append('  ' + ','.join(str(v) for v in words[i:i + 24]) + ',')
    lines += ['};', '', '} // namespace sandclock2', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('wrote %s: %d glyphs, %d words' % (OUT, len(glyphs), len(words)))


if __name__ == '__main__':
    main()
