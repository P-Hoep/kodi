"""Generate the settings.xml and strings.po of the Vintage Radar screensaver AND the Python app from
one table, plus the Python defaults used by the app's offline tests and the find-location command.

Run: python3 tools/make_settings_vintageradar.py
     python3 tools/make_settings_vintageradar.py screensaver.vintageradar.gl.armv7 'Vintage Radar (OpenGL, 32-bit Android)'

The optional first argument is the screensaver add-on id to write, so the 32-bit Android build can
carry the same settings under its own id. The Python app is always written as script.vintageradar.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, HERE)

from make_settings import write  # noqa: E402

B = lambda sid, label, default, **kw: dict(id=sid, type='boolean', label=label, default=default, **kw)
I = lambda sid, label, default, lo, hi, step=1, **kw: dict(
    id=sid, type='slider', label=label, default=default, min=lo, max=hi, step=step, **kw)
O = lambda sid, label, default, options, **kw: dict(
    id=sid, type='options', label=label, default=default, options=options, **kw)

CATEGORIES = [
    ('Location', [
        dict(id='location_name', type='string', label='Place name shown on screen', default='Home'),
        dict(id='find_location', type='action', label='Find a place by name...',
             data='RunScript(script.vintageradar,find_location)'),
        dict(id='latitude', type='number', label='Latitude (decimal degrees, south negative)',
             default='44.9031331'),
        dict(id='longitude', type='number', label='Longitude (decimal degrees, west negative)',
             default='-93.3096136'),
    ]),
    ('Scope', [
        I('range_km', 'Range of the scope (km)', 60, 5, 400, 5),
        O('units', 'Units', 1, ['Metric (km, m, km/h)', 'Aviation (nm, ft, kt)']),
        I('refresh_seconds', 'How often to fetch aircraft (seconds)', 20, 10, 120, 5),
        I('sweep_seconds', 'One sweep of the beam (seconds)', 6, 2, 12),
        B('show_ground', 'Show aircraft and vehicles on the ground', False),
        O('min_altitude', 'Lowest altitude to show', 0,
          ['All altitudes', '1,000 ft and above', '5,000 ft and above', '10,000 ft and above']),
    ]),
    ('Contacts', [
        B('show_labels', 'Label the contacts on the scope', True),
        O('label_detail', 'What a scope label shows', 1,
          ['Callsign only', 'Callsign + altitude and speed', 'Callsign + type and altitude']),
        B('show_history', 'Trail of past sweep echoes', True),
        I('max_contacts', 'Most contacts to track', 40, 5, 200, 5),
    ]),
    ('Information panel', [
        B('show_panel', 'Show the contact list and spotlight panel', True),
        I('detail_seconds', 'How long each contact holds the spotlight (seconds)', 10, 4, 60),
        I('list_seconds', 'How long the list follows the spotlight before paging back (seconds)', 8, 3, 60),
    ]),
    ('Look', [
        O('theme', 'Phosphor', 0, ['P1 green', 'P3 amber', 'P11 ice blue', 'White']),
        B('crt', 'CRT scanlines and vignette', True),
        I('dim', 'Dim the picture (%)', 0, 0, 40, 5),
        O('quality', 'Detail', 1, ['Low (for slow boxes)', 'Normal', 'High']),
    ]),
]

# The Python defaults module: exactly the table above, so the app and the screensaver agree.
DEFAULTS_HEADER = '''"""Generated by tools/make_settings_vintageradar.py; edit the table there.

The values are also what settings.xml carries, so the app behaves the same before the user has
touched anything and in offline tests where Kodi is not running.
"""

'''


def write_python_defaults():
    path = os.path.join(ROOT, 'script.vintageradar', 'resources', 'lib', 'defaults.py')
    lines = [DEFAULTS_HEADER]
    for _title, settings in CATEGORIES:
        for s in settings:
            if s['type'] == 'action':
                continue
            lines.append('%s = %r' % (s['id'], s['default']))
    lines.append('')
    lines.append('DEFAULTS = {')
    for _title, settings in CATEGORIES:
        for s in settings:
            if s['type'] == 'action':
                continue
            lines.append('    %r: %r,' % (s['id'], s['default']))
    lines += ['}', '', '']
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as handle:
        handle.write('\n'.join(lines))
    print('python defaults: %s' % path)


if __name__ == '__main__':
    addon = sys.argv[1] if len(sys.argv) > 1 else 'screensaver.vintageradar.gl'
    name = sys.argv[2] if len(sys.argv) > 2 else 'Vintage Radar (OpenGL)'
    write(os.path.join(ROOT, addon), addon, name, CATEGORIES, 'tools/make_settings_vintageradar.py')
    write(os.path.join(ROOT, 'script.vintageradar'), 'script.vintageradar',
          'Vintage Radar', CATEGORIES, 'tools/make_settings_vintageradar.py')
    write_python_defaults()
